CREATE TABLE "HR"."EMPLOYEES"
(	"EMP_ID" NUMBER(10,0) NOT NULL ENABLE,
	"DEPT_ID" NUMBER(10,0),
	"EMAIL" VARCHAR2(100 BYTE),
	 CONSTRAINT "EMP_PK" PRIMARY KEY ("EMP_ID"),
	 CONSTRAINT "EMP_DEPT_FK" FOREIGN KEY ("DEPT_ID")
	  REFERENCES "HR"."DEPARTMENTS" ("DEPT_ID") ENABLE
) SEGMENT CREATION IMMEDIATE
  TABLESPACE "USERS";

CREATE TABLE "HR"."DEPARTMENTS"
(	"DEPT_ID" NUMBER(10,0),
	"DEPT_NAME" VARCHAR2(50 BYTE)
);

CREATE OR REPLACE VIEW "HR"."V_EMP" AS
  SELECT e.EMP_ID, d.DEPT_NAME FROM "HR"."EMPLOYEES" e
  JOIN "HR"."DEPARTMENTS" d ON e.DEPT_ID = d.DEPT_ID;
